// Local development only: fill in missing secrets in apps/api/.env (gitignored).
//   pnpm --filter @alphakolect/api secrets:local
// Adds AUTH_SIGNING_JWK and MFA_ENCRYPTION_KEY when absent, and DATABASE_URL (as the least-privilege app role,
// using DB_APP_PASSWORD from infrastructure/.env) when absent. Existing values are never changed.
// Prints only the NAMES of what it added — never a value.
import { randomBytes, randomUUID } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { exportJWK, generateKeyPair } from 'jose';

if (process.env.NODE_ENV === 'production') {
  process.stderr.write('Refusing to generate secrets with NODE_ENV=production.\n');
  process.exit(1);
}

const envFile = new URL('../.env', import.meta.url);
const infraEnvFile = new URL('../../../infrastructure/.env', import.meta.url);

const current = existsSync(envFile) ? readFileSync(envFile, 'utf8') : '';
const has = (name: string) => new RegExp(`^${name}=.+`, 'm').test(current);
const additions: Array<[string, string]> = [];

if (!has('AUTH_SIGNING_JWK')) {
  const { privateKey } = await generateKeyPair('EdDSA', { crv: 'Ed25519', extractable: true });
  const jwk = await exportJWK(privateKey);
  const kid = `local-${randomUUID().slice(0, 8)}`;
  additions.push([
    'AUTH_SIGNING_JWK',
    JSON.stringify({ kty: 'OKP', crv: 'Ed25519', d: jwk.d, x: jwk.x, kid }),
  ]);
}

if (!has('MFA_ENCRYPTION_KEY')) {
  additions.push([
    'MFA_ENCRYPTION_KEY',
    `local-${randomUUID().slice(0, 8)}:${randomBytes(32).toString('base64')}`,
  ]);
}

if (!has('DATABASE_URL')) {
  const infra = existsSync(infraEnvFile) ? readFileSync(infraEnvFile, 'utf8') : '';
  const password = /^DB_APP_PASSWORD=(.+)$/m.exec(infra)?.[1]?.trim();
  if (password) {
    additions.push([
      'DATABASE_URL',
      `postgresql://alphakolect_app:${encodeURIComponent(password)}@127.0.0.1:5436/alphakolect`,
    ]);
  } else {
    process.stderr.write('DATABASE_URL not added: set DB_APP_PASSWORD in infrastructure/.env first.\n');
  }
}

if (additions.length === 0) {
  process.stdout.write('apps/api/.env already has every generated secret; nothing changed.\n');
} else {
  const prefix =
    current === ''
      ? '# LOCAL ONLY — generated by secrets:local. Never commit.\n'
      : current.endsWith('\n')
        ? ''
        : '\n';
  writeFileSync(envFile, current + prefix + additions.map(([k, v]) => `${k}=${v}`).join('\n') + '\n', {
    mode: 0o600,
  });
  process.stdout.write(`Added to apps/api/.env: ${additions.map(([k]) => k).join(', ')}\n`);
}
